// DRAW 3D FACE MESH & BIOMETRIC AXES ON OVERLAY CANVAS
// ═══════════════════════════════════════════════════════════════════════════
function draw3DFaceMeshOverlay(landmarks) {
    const img = document.getElementById('preview-img');
    const canvas = document.getElementById('mesh-canvas');
    const badge = document.getElementById('mesh-status-badge');
    if (!img || !canvas || !landmarks || !landmarks.length) return;

    const rect = img.getBoundingClientRect();
    const w = Math.max(320, Math.round(rect.width || img.naturalWidth || 400));
    const h = Math.max(320, Math.round(rect.height || img.naturalHeight || 400));
    canvas.width = w;
    canvas.height = h;

    // Compute object-fit: contain offset inside img element
    const natW = img.naturalWidth || w;
    const natH = img.naturalHeight || h;
    const scale = Math.min(w / natW, h / natH);
    const drawW = natW * scale;
    const drawH = natH * scale;
    const offX = (w - drawW) / 2;
    const offY = (h - drawH) / 2;

    const px = idx => offX + landmarks[idx].x * drawW;
    const py = idx => offY + landmarks[idx].y * drawH;

    const ctx = canvas.getContext('2d');
    ctx.clearRect(0, 0, w, h);

    // 1. Subtle dark vignette over photo for high-contrast biometric lines
    ctx.fillStyle = 'rgba(6, 10, 22, 0.18)';
    ctx.fillRect(offX, offY, drawW, drawH);

    // 2. Face Oval Contour (36 anatomical perimeter points)
    const OVAL_RING = [10, 338, 297, 332, 284, 251, 389, 356, 454, 323, 361, 288, 397, 365, 379, 378, 400, 377, 152, 148, 176, 149, 150, 136, 172, 58, 132, 93, 234, 127, 162, 21, 54, 103, 67, 109, 10];
    ctx.save();
    ctx.strokeStyle = 'rgba(94, 106, 210, 0.78)';
    ctx.lineWidth = 1.8;
    ctx.beginPath();
    OVAL_RING.forEach((ptIdx, i) => {
        if (!landmarks[ptIdx]) return;
        const x = px(ptIdx), y = py(ptIdx);
        if (i === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
    });
    ctx.stroke();
    ctx.restore();

    // 3. All 478 3D Mesh Dots
    ctx.save();
    ctx.fillStyle = 'rgba(147, 197, 253, 0.58)';
    for (let i = 0; i < landmarks.length; i++) {
        const x = offX + landmarks[i].x * drawW;
        const y = offY + landmarks[i].y * drawH;
        ctx.beginPath();
        ctx.arc(x, y, 1.15, 0, Math.PI * 2);
        ctx.fill();
    }
    ctx.restore();

    // 4. Key Biometric Measurement Axes (Forehead, Cheekbones, Jawline, Face Height)
    const drawAxisLine = (idxA, idxB, color, dashed) => {
        if (!landmarks[idxA] || !landmarks[idxB]) return;
        const x1 = px(idxA), y1 = py(idxA);
        const x2 = px(idxB), y2 = py(idxB);
        ctx.save();
        ctx.strokeStyle = color;
        ctx.lineWidth = 2.2;
        if (dashed) ctx.setLineDash([5, 4]);
        ctx.beginPath();
        ctx.moveTo(x1, y1);
        ctx.lineTo(x2, y2);
        ctx.stroke();

        // Glowing endpoint nodes
        ctx.setLineDash([]);
        ctx.fillStyle = color;
        [ [x1, y1], [x2, y2] ].forEach(([cx, cy]) => {
            ctx.beginPath();
            ctx.arc(cx, cy, 3.8, 0, Math.PI * 2);
            ctx.fill();
        });
        ctx.restore();
    };

    // Vertical Height Axis (#10 Forehead -> #152 Chin)
    drawAxisLine(10, 152, 'rgba(255, 255, 255, 0.75)', true);
    // Forehead Width (#54 -> #284)
    drawAxisLine(54, 284, '#38bdf8', false);
    // Cheekbone Width (#234 -> #454)
    drawAxisLine(234, 454, '#10b981', false);
    // Jawline Width (#172 -> #397)
    drawAxisLine(172, 397, '#f59e0b', false);

    if (badge) {
        badge.textContent = (i18n[currentLang] && i18n[currentLang].badge_scanned) || '🧬 Google MediaPipe 3D Face Mesh · 478 точек';
        badge.style.display = 'block';
    }
}

