// DRAW PHOTO + REAL 3D FACE MESH & BIOMETRIC AXES ON THE SAME CANVAS
// ═══════════════════════════════════════════════════════════════════════════
function draw3DFaceMeshOverlay(landmarks) {
    const canvas = document.getElementById('mesh-canvas');
    const badge = document.getElementById('mesh-status-badge');
    if (!canvas || !preparedScanCanvas || !landmarks || !landmarks.length) return;

    currentLandmarks = landmarks;
    const w = preparedScanCanvas.width;
    const h = preparedScanCanvas.height;
    canvas.width = w;
    canvas.height = h;

    const px = idx => landmarks[idx].x * w;
    const py = idx => landmarks[idx].y * h;

    const ctx = canvas.getContext('2d');
    ctx.clearRect(0, 0, w, h);

    // 1. Draw the base photo into the exact same coordinate space
    ctx.drawImage(preparedScanCanvas, 0, 0, w, h);

    // 2. Subtle biometric darkening overlay so lines pop cleanly
    ctx.fillStyle = 'rgba(6, 10, 22, 0.22)';
    ctx.fillRect(0, 0, w, h);

    const drawPath = (indices, strokeStyle, lineWidth, closeLoop) => {
        ctx.save();
        ctx.strokeStyle = strokeStyle;
        ctx.lineWidth = lineWidth;
        ctx.lineJoin = 'round';
        ctx.lineCap = 'round';
        ctx.beginPath();
        let started = false;
        for (let i = 0; i < indices.length; i++) {
            const pt = landmarks[indices[i]];
            if (!pt) continue;
            const x = pt.x * w, y = pt.y * h;
            if (!started) {
                ctx.moveTo(x, y);
                started = true;
            } else {
                ctx.lineTo(x, y);
            }
        }
        if (closeLoop && started) ctx.closePath();
        ctx.stroke();
        ctx.restore();
    };

    // 3. Anatomical Contours (Face Oval, Eyebrows, Eyes, Nose Bridge, Lips, Structural Triangles)
    const OVAL_RING = [10, 338, 297, 332, 284, 251, 389, 356, 454, 323, 361, 288, 397, 365, 379, 378, 400, 377, 152, 148, 176, 149, 150, 136, 172, 58, 132, 93, 234, 127, 162, 21, 54, 103, 67, 109];
    const LEFT_EYE = [33, 160, 158, 133, 153, 144];
    const RIGHT_EYE = [263, 387, 385, 362, 380, 373];
    const LEFT_BROW = [70, 63, 105, 66, 107];
    const RIGHT_BROW = [300, 293, 334, 296, 336];
    const NOSE_BRIDGE = [168, 6, 197, 195, 5, 4, 1];
    const LIPS_OUTER = [61, 185, 40, 39, 37, 0, 267, 269, 270, 409, 291, 375, 321, 405, 314, 17, 84, 181, 91, 146];

    // Symmetric 3D structural wireframe lines across cheeks/forehead/jaw
    const WIREFRAME_PAIRS = [
        [10, 103], [10, 332], [103, 54], [332, 284],
        [54, 234], [284, 454], [234, 172], [454, 397],
        [172, 152], [397, 152], [168, 103], [168, 332],
        [168, 234], [168, 454], [1, 234], [1, 454],
        [1, 172], [1, 397], [33, 234], [263, 454]
    ];
    WIREFRAME_PAIRS.forEach(pair => drawPath(pair, 'rgba(147, 197, 253, 0.28)', 1.1, false));

    drawPath(OVAL_RING, 'rgba(94, 106, 210, 0.85)', 2.0, true);
    drawPath(LEFT_EYE, 'rgba(56, 189, 248, 0.75)', 1.4, true);
    drawPath(RIGHT_EYE, 'rgba(56, 189, 248, 0.75)', 1.4, true);
    drawPath(LEFT_BROW, 'rgba(147, 197, 253, 0.65)', 1.4, false);
    drawPath(RIGHT_BROW, 'rgba(147, 197, 253, 0.65)', 1.4, false);
    drawPath(NOSE_BRIDGE, 'rgba(147, 197, 253, 0.65)', 1.4, false);
    drawPath(LIPS_OUTER, 'rgba(167, 139, 250, 0.65)', 1.3, true);

    // 4. All 478 3D Landmark Dots
    ctx.save();
    ctx.fillStyle = 'rgba(191, 219, 254, 0.72)';
    for (let i = 0; i < landmarks.length; i++) {
        if (!landmarks[i]) continue;
        const x = landmarks[i].x * w;
        const y = landmarks[i].y * h;
        ctx.beginPath();
        ctx.arc(x, y, 1.35, 0, Math.PI * 2);
        ctx.fill();
    }
    ctx.restore();

    // 5. Key Biometric Measurement Axes (Forehead, Cheekbones, Jawline, Face Height)
    const t = i18n[currentLang] || i18n.ru;
    const drawAxisLine = (idxA, idxB, color, dashed, labelText) => {
        if (!landmarks[idxA] || !landmarks[idxB]) return;
        const x1 = px(idxA), y1 = py(idxA);
        const x2 = px(idxB), y2 = py(idxB);
        ctx.save();
        ctx.strokeStyle = color;
        ctx.lineWidth = 2.4;
        if (dashed) ctx.setLineDash([6, 4]);
        ctx.beginPath();
        ctx.moveTo(x1, y1);
        ctx.lineTo(x2, y2);
        ctx.stroke();

        // Glowing endpoint nodes
        ctx.setLineDash([]);
        ctx.fillStyle = color;
        [[x1, y1], [x2, y2]].forEach(([cx, cy]) => {
            ctx.beginPath();
            ctx.arc(cx, cy, 4.2, 0, Math.PI * 2);
            ctx.fill();
            ctx.strokeStyle = '#09090d';
            ctx.lineWidth = 1.2;
            ctx.stroke();
        });

        if (labelText) {
            ctx.font = 'bold 11px sans-serif';
            const tw = ctx.measureText(labelText).width;
            const lx = Math.min(w - tw - 14, Math.max(6, Math.max(x1, x2) + 8));
            const ly = (y1 + y2) / 2;
            ctx.fillStyle = 'rgba(9, 9, 16, 0.82)';
            ctx.fillRect(lx - 4, ly - 9, tw + 8, 16);
            ctx.fillStyle = color;
            ctx.fillText(labelText, lx, ly + 3);
        }
        ctx.restore();
    };

    // Vertical Height Axis (#10 Forehead -> #152 Chin)
    drawAxisLine(10, 152, 'rgba(255, 255, 255, 0.82)', true, '');
    // Forehead Width (#54 -> #284)
    drawAxisLine(54, 284, '#38bdf8', false, t.axis_fh);
    // Cheekbone Width (#234 -> #454)
    drawAxisLine(234, 454, '#10b981', false, t.axis_cheek);
    // Jawline Width (#172 -> #397)
    drawAxisLine(172, 397, '#f59e0b', false, t.axis_jaw);

    if (badge) {
        badge.textContent = t.badge_scanned || '🧬 Google MediaPipe 3D Face Mesh · 478 точек';
        badge.style.display = 'block';
    }
}

