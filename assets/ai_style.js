function handleFileSelect(event) {
    const file = event.target.files[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (e) => {
        const dataUrl = e.target.result;
        const img = document.getElementById('preview-img');
        const wrap = document.getElementById('preview-wrap');
        const canvas = document.getElementById('mesh-canvas');
        const badge = document.getElementById('mesh-status-badge');

        if (badge) badge.style.display = 'none';
        currentLandmarks = null;

        img.onload = () => {
            // Create normalized scanCanvas (max 640px) so photo and 3D landmarks share 1:1 pixel space
            const maxDim = 640;
            let w = img.naturalWidth || img.width || 480;
            let h = img.naturalHeight || img.height || 640;
            if (w > maxDim || h > maxDim) {
                if (w > h) {
                    h = Math.round((h * maxDim) / w);
                    w = maxDim;
                } else {
                    w = Math.round((w * maxDim) / h);
                    h = maxDim;
                }
            }
            const offscreen = document.createElement('canvas');
            offscreen.width = w;
            offscreen.height = h;
            offscreen.getContext('2d').drawImage(img, 0, 0, w, h);
            preparedScanCanvas = offscreen;

            // Render clean photo directly onto #mesh-canvas
            if (canvas) {
                canvas.width = w;
                canvas.height = h;
                const ctx = canvas.getContext('2d');
                ctx.clearRect(0, 0, w, h);
                ctx.drawImage(offscreen, 0, 0, w, h);
            }

            if (wrap) wrap.style.display = 'block';
            const zone = document.getElementById('upload-zone');
            zone.classList.add('has-image');
            zone.querySelector('.upload-icon').style.display = 'none';
            zone.querySelector('h3').style.display = 'none';
            zone.querySelector('p').style.display = 'none';
            document.getElementById('analyze-btn').disabled = false;
        };
        img.src = dataUrl;
        hideError();
    };
    reader.readAsDataURL(file);
}

