function changeLanguage(lang) {
    if (!i18n[lang]) lang = 'ru';
    currentLang = lang;
    localStorage.setItem('barber_lang', lang);
    localStorage.setItem('adminLang', lang);
    const sel = document.getElementById('lang-select');
    if (sel) sel.value = lang;
    if (window.BarberCurrency) window.BarberCurrency.syncByLang(lang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[lang] && i18n[lang][key]) el.innerHTML = i18n[lang][key];
    });
    const badge = document.getElementById('mesh-status-badge');
    if (badge && i18n[lang].badge_scanned) {
        badge.textContent = i18n[lang].badge_scanned;
    }
    if (currentLandmarks && preparedScanCanvas) {
        draw3DFaceMeshOverlay(currentLandmarks);
    }
    if (currentFaceData) {
        renderResults(currentFaceData);
    }
}

